/**
 * Retorna o componente de ícone baseado no tipo
 */
export function getFileIcon(iconType, className = 'w-5 h-5') {
    const icons = {
        image: ImageIcon,
        pdf: PdfIcon,
        spreadsheet: SpreadsheetIcon,
        document: DocumentIcon,
        file: FileIcon,
    };

    const IconComponent = icons[iconType] || FileIcon;
    return <IconComponent className={className} />;
}

/**
 * Retorna a cor do ícone baseado no tipo
 */
export function getFileIconColor(iconType) {
    const colors = {
        image: 'text-blue-500 dark:text-blue-400',
        pdf: 'text-red-500 dark:text-red-400',
        spreadsheet: 'text-green-500 dark:text-green-400',
        document: 'text-indigo-500 dark:text-indigo-400',
        file: 'text-gray-500 dark:text-gray-400',
    };

    return colors[iconType] || colors.file;
}
